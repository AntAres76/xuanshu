  function whyPlaced(name, r) {
    var b = pos(r, name); if (b == null) return '';
    var hz = r.hourZhi, mo = r.month, day = r.day, yg = r.yearGan, yz = r.yearZhi, s = '';
    if (ZW.ZW_SERIES[name] != null) {
      if (name === '紫微') s = r.juName + '，生日 ' + day + '：' + zwFormula(r) + ' → <b>' + Z[b] + '</b> 宫。';
      else s = '紫微系：从紫微（' + zOf(r, '紫微') + '）' + '逆行 ' + (-ZW.ZW_SERIES[name]) + ' 宫 → <b>' + Z[b] + '</b> 宫。';
    } else if (ZW.TF_SERIES[name] != null) {
      if (name === '天府') s = '天府与紫微以寅申为轴对称：紫微在 ' + zOf(r, '紫微') + ' → 天府在 <b>' + Z[b] + '</b> 宫。';
      else s = '天府系：从天府（' + zOf(r, '天府') + '）顺行 ' + ZW.TF_SERIES[name] + ' 宫 → <b>' + Z[b] + '</b> 宫。';
    } else if (A[name]) {
      s = A[name].how + '<br>本盘：生年 ' + yg + yz + '、生月 ' + mo + '（' + (r.L.leap ? '闰月按设置调整' : '农历月') + '）、生时 ' + hz + ' → <b>' + Z[b] + '</b> 宫。';
    } else if (MISC[name]) {
      s = MISC[name][1] + '<br>本盘 → <b>' + Z[b] + '</b> 宫' + (name === '截路' || name === '旬空' ? '（共占两宫）' : '') + '。';
    }
    return s;
  }
