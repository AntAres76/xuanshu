  function pad(n) { return (n < 10 ? '0' : '') + n; }

  /** 用 UTC 字段承载“当地墙上时间”，避免浏览器所在时区干扰 */
  function mk(y, m, d, h, mi, s) { return new Date(Date.UTC(y, m - 1, d, h || 0, mi || 0, s || 0)); }
  function parts(dt) {
    return { y: dt.getUTCFullYear(), m: dt.getUTCMonth() + 1, d: dt.getUTCDate(), h: dt.getUTCHours(), mi: dt.getUTCMinutes(), s: dt.getUTCSeconds() };
  }
  function addMinutes(dt, min) { return new Date(dt.getTime() + Math.round(min * 60000)); }
  function fmt(dt, withSec) {
    var p = parts(dt);
    return p.y + '-' + pad(p.m) + '-' + pad(p.d) + ' ' + pad(p.h) + ':' + pad(p.mi) + (withSec ? ':' + pad(p.s) : '');
  }

  /** 均时差（分钟），近似公式，误差约 ±30 秒 */
  function equationOfTime(dt) {
    var start = Date.UTC(dt.getUTCFullYear(), 0, 1);
    var n = Math.floor((dt.getTime() - start) / 86400000) + 1;
    var b = 2 * Math.PI * (n - 81) / 364;
    return 9.87 * Math.sin(2 * b) - 7.53 * Math.cos(b) - 1.5 * Math.sin(b);
  }

  /** 中国 1986–1991 年夏令时区间（北京时间，凌晨2点起止） */
  var CN_DST = {
    1986: ['05-04', '09-14'], 1987: ['04-12', '09-13'], 1988: ['04-10', '09-11'],
    1989: ['04-16', '09-17'], 1990: ['04-15', '09-16'], 1991: ['04-14', '09-15']
  };
  function inChinaDST(y, m, d, h) {
    var r = CN_DST[y];
    if (!r) return false;
    var cur = mk(y, m, d, h, 0).getTime();
    var a = r[0].split('-'), b = r[1].split('-');
    var s = mk(y, +a[0], +a[1], 2).getTime(), e = mk(y, +b[0], +b[1], 2).getTime();
    return cur >= s && cur < e;
  }

  /**
   * 从钟表时间换算真太阳时。
   * opt: {longitude, tz(小时), dst(bool), trueSolar(bool)}
   * 返回 {clock, standard, mean, apparent, used, notes}
   */
  function adjust(y, m, d, h, mi, opt) {
    opt = opt || {};
    var clock = mk(y, m, d, h, mi);
    var notes = [];
    var std = clock;
    if (opt.dst) { std = addMinutes(clock, -60); notes.push('夏令时 −60 分'); }
    if (!opt.trueSolar || opt.longitude == null || isNaN(opt.longitude)) {
      return { clock: clock, used: std, notes: notes, trueSolar: false };
    }
    var tz = opt.tz == null ? 8 : opt.tz;
    var lonDiff = (opt.longitude - tz * 15) * 4;
    var mean = addMinutes(std, lonDiff);
    var eot = equationOfTime(mean);
    var app = addMinutes(mean, eot);
    notes.push('经度差 ' + (lonDiff >= 0 ? '+' : '') + lonDiff.toFixed(1) + ' 分');
    notes.push('均时差 ' + (eot >= 0 ? '+' : '') + eot.toFixed(1) + ' 分');
    return { clock: clock, mean: mean, apparent: app, used: app, notes: notes, trueSolar: true, lonDiff: lonDiff, eot: eot };
  }

